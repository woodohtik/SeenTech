-- =============================================================================
-- seen-verticals-readiness-task.md Phase 1: explicit capabilities instead of a
-- single "men's tailoring or not" flag.
--
--  1. verticals.capabilities (body_measurements, fabric_consumption,
--     sells_by_length, order_dimensions, orders_module, workshop_term,
--     item_term) and verticals.name_ur.
--  2. vertical_workflow_stages: phase (received | in_progress | ready |
--     delivered | cancelled), legacy_status (the order_status enum value the
--     stage writes to orders.status), consumes_materials (the stage where
--     material is deducted), label_en, label_ur. Every one of the 41 rows set
--     by hand (scripts/verticals/phase1_data.py); mens_tailoring maps to the
--     enum unchanged.
--  3. Translations: label_en / label_ur on fields and inventory categories,
--     options_i18n ({en: [...], ur: [...]}, same order as the stored Arabic
--     options -- the stored value stays Arabic).
--  4. measure_kind (length | count) on vertical_inventory_categories and
--     tenant_categories. mens_tailoring: only `fabric` is length, as today.
--  5. Furniture (founder question 6 default): numeric width / depth / height
--     (cm), number of pieces, design notes; the old free-text `dimensions`
--     field is removed only if no order uses it.
-- Data only for what the app reads; no order or shop row changes here (the
-- existing non-men's orders are fixed separately, 20261231000002).
-- Rollback: supabase/rollbacks/20261231_verticals_capabilities.down.sql.
-- =============================================================================

