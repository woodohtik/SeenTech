-- A shop's own categories: the measure of the same key in its vertical;
-- otherwise the old rule (only `fabric` is measured by length).
-- Only the rows whose value changes are written.
WITH wanted AS (
  SELECT tc.id,
         COALESCE(
           (SELECT vc.measure_kind FROM public.vertical_inventory_categories vc
              JOIN public.tenants t ON t.vertical = vc.vertical_key
             WHERE t.id = tc.tenant_id AND vc.category_key = tc.category_key),
           CASE WHEN tc.category_key = 'fabric' THEN 'length' ELSE 'count' END) AS kind
    FROM public.tenant_categories tc
   WHERE tc.scope = 'inventory'
)
UPDATE public.tenant_categories tc
   SET measure_kind = w.kind
  FROM wanted w
 WHERE tc.id = w.id AND tc.measure_kind IS DISTINCT FROM w.kind;

-- Every stage is now described; refuse to finish otherwise.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.vertical_workflow_stages WHERE phase IS NULL OR legacy_status IS NULL OR label_en IS NULL OR label_ur IS NULL) THEN
    RAISE EXCEPTION 'vertical_workflow_stages: a stage was left without phase / legacy_status / labels';
  END IF;
  IF EXISTS (SELECT 1 FROM public.verticals WHERE capabilities IS NULL OR name_ur IS NULL) THEN
    RAISE EXCEPTION 'verticals: capabilities or name_ur missing';
  END IF;
  IF EXISTS (SELECT 1 FROM public.vertical_field_schemas WHERE label_en IS NULL OR label_ur IS NULL) THEN
    RAISE EXCEPTION 'vertical_field_schemas: a label is missing';
  END IF;
  IF EXISTS (SELECT 1 FROM public.vertical_field_schemas WHERE field_type = 'select' AND options_i18n IS NULL AND jsonb_array_length(coalesce(options, '[]'::jsonb)) > 0) THEN
    RAISE EXCEPTION 'vertical_field_schemas: select options not translated';
  END IF;
  IF EXISTS (SELECT 1 FROM public.vertical_inventory_categories WHERE label_en IS NULL OR label_ur IS NULL) THEN
    RAISE EXCEPTION 'vertical_inventory_categories: a label is missing';
  END IF;
  -- mens_tailoring keeps the enum it always wrote.
  IF EXISTS (SELECT 1 FROM public.vertical_workflow_stages WHERE vertical_key = 'mens_tailoring' AND legacy_status::text <> stage_key) THEN
    RAISE EXCEPTION 'mens_tailoring: a stage does not map to its own enum value';
  END IF;
END
$$;

ALTER TABLE public.vertical_workflow_stages ALTER COLUMN phase SET NOT NULL;
ALTER TABLE public.vertical_workflow_stages ALTER COLUMN legacy_status SET NOT NULL;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'vertical_workflow_stages_phase_check') THEN
    ALTER TABLE public.vertical_workflow_stages ADD CONSTRAINT vertical_workflow_stages_phase_check
      CHECK (phase IN ('received', 'in_progress', 'ready', 'delivered', 'cancelled'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'vertical_inventory_categories_measure_kind_check') THEN
    ALTER TABLE public.vertical_inventory_categories ADD CONSTRAINT vertical_inventory_categories_measure_kind_check
      CHECK (measure_kind IN ('length', 'count'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tenant_categories_measure_kind_check') THEN
    ALTER TABLE public.tenant_categories ADD CONSTRAINT tenant_categories_measure_kind_check
      CHECK (measure_kind IN ('length', 'count'));
  END IF;
END
$$;
