-- Rewrites the SELECT RLS policies on suppliers and supplier_transactions to
-- gate on suppliers.manage (via app_has_permission() from Task 1) instead of
-- a bare tenant_id check -- today, any tenant staff member (including a
-- cashier who is never shown the /suppliers screen) can read the full
-- supplier list and ledger directly via supabase.select(), bypassing the
-- client-side UI gate entirely.
--
-- payments.view_prices is explicitly OUT of scope for this task -- it was
-- in the original brainstorming discussion as an example, but never made
-- the plan's final 11 approved permission keys (see task-7-brief.md's own
-- Step 3 note, and the spec's Section 1.1 list). payments' SELECT policy
-- is left untouched.
--
-- True current/live policy names, confirmed by grepping ALL migrations
-- (not trusting the brief's claim about "current state" at face value, per
-- the lesson from Task 6's review):
--
--   suppliers_tenant_read: generated by the %I_tenant_read format string in
--   the tenant_tables loop (20240601000000_track_base_schema.sql), never
--   overridden since. Previously:
--     app_is_super_admin() OR tenant_id = app_current_tenant_id()
--
--   supplier_transactions_tenant_select: created in
--   20261121000000_supplier_balance_role_guard.sql, which split the earlier
--   supplier_transactions_tenant_isolation FOR ALL policy (itself from
--   20261019020000_missing_tables_schema_drift.sql) into per-command
--   policies. Never overridden since. Previously:
--     app_is_super_admin() OR tenant_id = app_current_tenant_id()
--
-- Both DROP targets above were verified against the full migration history
-- up through 20261210000000 (the most recent migration before this one) --
-- no other migration touches either table's SELECT policy.

DROP POLICY IF EXISTS suppliers_tenant_read ON suppliers;
CREATE POLICY suppliers_tenant_read ON suppliers
    FOR SELECT USING (
        app_is_super_admin()
        OR (
            tenant_id = app_current_tenant_id()
            AND app_has_permission('suppliers.manage')
        )
    );

DROP POLICY IF EXISTS supplier_transactions_tenant_select ON public.supplier_transactions;
CREATE POLICY supplier_transactions_tenant_select ON public.supplier_transactions
    FOR SELECT TO authenticated
    USING (
        app_is_super_admin()
        OR (
            tenant_id = app_current_tenant_id()
            AND app_has_permission('suppliers.manage')
        )
    );
