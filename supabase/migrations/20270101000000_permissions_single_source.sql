-- seen-permissions-fix-task.md Phase 1: one source of permissions.
--
-- Before this, three places decided permissions differently: the UI
-- (DEFAULT_ROLES, then the shop's roles row by role_key, then overrides), the
-- database (staff.role_id only, then a fixed table of 12 keys, then
-- overrides) and server.ts (role lists). Now:
--
--  1. public.role_default_permissions: the eight roles' defaults for all 50
--     keys, generated from src/shared/permissionsMatrix.json (the same file
--     the UI's DEFAULT_ROLES is built from). For the 12 keys the server
--     checked before, the values equal app_default_permission's
--     (permissions_single_source_test.sql checks every role).
--  2. public.app_effective_permissions(staff_id): the one decision --
--       owner -> every key;
--       role row: staff.role_id if set, else the shop's roles row with
--       role_key = staff.role (what the settings screen edits), else the
--       system row; its keys win over the defaults;
--       then the staff member's own overrides.
--     app_has_permission(key) reads it.
--  3. public.get_my_permissions(): the map for the caller, for the UI.
--  4. roles.base_role: a custom role's nearest built-in role, saved as
--     staff.role for its members instead of always 'tailor'.
--
-- app_default_permission is left as it was (no longer called) so the test
-- can compare against it. Rollback:
-- supabase/rollbacks/20270101_permissions_single_source.down.sql

