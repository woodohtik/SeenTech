-- 2. Custom roles: the nearest built-in role --------------------------------
ALTER TABLE public.roles ADD COLUMN IF NOT EXISTS base_role text;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'roles_base_role_check') THEN
    ALTER TABLE public.roles ADD CONSTRAINT roles_base_role_check
      CHECK (base_role IS NULL OR base_role IN ('admin', 'manager', 'branch_manager', 'accountant', 'warehouse_manager', 'cashier', 'tailor'));
  END IF;
END $$;

-- 3. The decision -------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.app_effective_permissions(p_staff_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_staff     record;
  v_defaults  jsonb;
  v_role_perm jsonb;
  v_overrides jsonb;
BEGIN
  SELECT id, tenant_id, role::text AS role, role_id INTO v_staff FROM public.staff WHERE id = p_staff_id;
  IF NOT FOUND THEN RETURN '{}'::jsonb; END IF;

  IF v_staff.role = 'owner' THEN
    RETURN (SELECT coalesce(jsonb_object_agg(permission_key, true), '{}'::jsonb)
              FROM public.role_default_permissions WHERE role_key = 'owner');
  END IF;

  SELECT coalesce(jsonb_object_agg(permission_key, allowed), '{}'::jsonb) INTO v_defaults
    FROM public.role_default_permissions WHERE role_key = v_staff.role;

  IF v_staff.role_id IS NOT NULL THEN
    SELECT permissions INTO v_role_perm FROM public.roles WHERE id = v_staff.role_id;
  END IF;
  IF v_role_perm IS NULL THEN
    SELECT permissions INTO v_role_perm FROM public.roles
     WHERE tenant_id = v_staff.tenant_id AND role_key = v_staff.role;
  END IF;
  IF v_role_perm IS NULL THEN
    SELECT permissions INTO v_role_perm FROM public.roles
     WHERE tenant_id IS NULL AND role_key = v_staff.role;
  END IF;

  SELECT overrides INTO v_overrides FROM public.user_permission_overrides WHERE staff_id = v_staff.id;

  -- Later layers win key by key; non-boolean junk in a JSONB opinion reads as false.
  RETURN (
    SELECT coalesce(jsonb_object_agg(k, CASE WHEN jsonb_typeof(v) = 'boolean' THEN v ELSE 'false'::jsonb END), '{}'::jsonb)
      FROM jsonb_each(v_defaults || coalesce(v_role_perm, '{}'::jsonb) || coalesce(v_overrides, '{}'::jsonb)) AS e(k, v)
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.app_effective_permissions(uuid) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.app_has_permission(p_permission_key text)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_role     text;
  v_staff_id uuid;
BEGIN
  IF app_is_super_admin() THEN RETURN true; END IF;

  v_role := app_current_role();
  IF v_role = 'owner' THEN RETURN true; END IF;
  IF v_role IS NULL THEN RETURN false; END IF;

  v_staff_id := app_current_staff_id();
  IF v_staff_id IS NULL THEN RETURN false; END IF;

  RETURN coalesce((public.app_effective_permissions(v_staff_id) ->> p_permission_key)::boolean, false);
END;
$function$;

-- 4. For the UI ----------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.get_my_permissions()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_staff_id uuid;
  v_role     text;
  v_all      jsonb;
BEGIN
  SELECT coalesce(jsonb_object_agg(permission_key, true), '{}'::jsonb) INTO v_all
    FROM public.role_default_permissions WHERE role_key = 'owner';

  IF app_is_super_admin() THEN
    RETURN jsonb_build_object('staff_id', NULL, 'role', 'super_admin', 'permissions', v_all);
  END IF;

  v_role := app_current_role();
  IF v_role IS NULL THEN RAISE EXCEPTION 'forbidden' USING ERRCODE = '42501'; END IF;
  v_staff_id := app_current_staff_id();

  IF v_role = 'owner' THEN
    RETURN jsonb_build_object('staff_id', v_staff_id, 'role', 'owner', 'permissions', v_all);
  END IF;

  RETURN jsonb_build_object(
    'staff_id', v_staff_id,
    'role', v_role,
    'role_id', (SELECT role_id FROM public.staff WHERE id = v_staff_id),
    'permissions', public.app_effective_permissions(v_staff_id)
  );
END;
