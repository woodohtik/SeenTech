-- (follow-up finding surfaced during Fix-B's review).
--
-- Fix-B (20261214000000_supplier_transactions_write_permission_check.sql)
-- gated supplier_transactions' write policies on suppliers.manage. Its
-- reviewer separately flagged that the suppliers TABLE ITSELF has no role
-- or permission check at all on its own INSERT/UPDATE/DELETE policies --
-- confirmed via grep, no migration has ever named suppliers_tenant_insert/
-- _update/_delete explicitly, so they come purely from the generic loop in
-- 20240601000000_track_base_schema.sql (tenant_tables array includes
-- 'suppliers', lines ~1065/1092-1138), which only checks
-- tenant_id = app_current_tenant_id().
--
-- Confirmed via grep (supabase/migrations) that the only migration to ever
-- touch any suppliers_tenant_* policy name since the base schema is
-- 20261211000000_select_policies_permission_based.sql, and that one only
-- rewrote suppliers_tenant_read (Task 7) -- suppliers_tenant_insert/
-- _update/_delete are untouched by any migration before this one, so the
-- live definitions match the base-schema loop's generic template exactly.
--
-- That means any authenticated tenant staff member -- including a cashier
-- -- could write DIRECTLY to suppliers (including its balance column) via
-- a plain UPDATE suppliers SET balance = ..., completely bypassing both the
-- RPCs (issue_supplier_payment/increment_supplier_balance, gated in Task 5)
-- and the suppliers.manage permission entirely. Same financial-integrity
-- risk class as the original C2 finding (Task 5+7 ledger gap), but even
-- more direct -- it skips the RPCs' own business logic (idempotency,
-- ledger-row creation) too. (In practice, Task 7's suppliers_tenant_read
-- rewrite already closes the UPDATE/DELETE half of this indirectly, since
-- Postgres consults the SELECT policy to find existing rows for an
-- UPDATE/DELETE's WHERE clause -- but INSERT doesn't depend on SELECT
-- visibility at all, so a direct INSERT into suppliers remains exploitable
-- today regardless. The founder asked for the identical suppliers.manage
-- gate on all three write policies anyway, for direct, non-incidental
-- enforcement and symmetry with Fix-B.)
--
-- Fix (founder-approved): apply the identical suppliers.manage gate to
-- suppliers' own INSERT/UPDATE/DELETE policies, same pattern as Fix-B used
-- for supplier_transactions. Structure is preserved exactly from the live
-- definitions (generated by the base-schema loop) -- only the plain
-- tenant_id = app_current_tenant_id() condition is extended with
-- AND public.app_has_permission('suppliers.manage').

DROP POLICY IF EXISTS suppliers_tenant_insert ON public.suppliers;
CREATE POLICY suppliers_tenant_insert ON public.suppliers
    FOR INSERT WITH CHECK (
        app_is_super_admin() OR (tenant_id = app_current_tenant_id() AND public.app_has_permission('suppliers.manage'))
    );

DROP POLICY IF EXISTS suppliers_tenant_update ON public.suppliers;
CREATE POLICY suppliers_tenant_update ON public.suppliers
    FOR UPDATE USING (
        app_is_super_admin() OR (tenant_id = app_current_tenant_id() AND public.app_has_permission('suppliers.manage'))
    )
    WITH CHECK (
        app_is_super_admin() OR (tenant_id = app_current_tenant_id() AND public.app_has_permission('suppliers.manage'))
    );

DROP POLICY IF EXISTS suppliers_tenant_delete ON public.suppliers;
CREATE POLICY suppliers_tenant_delete ON public.suppliers
    FOR DELETE USING (
        app_is_super_admin() OR (tenant_id = app_current_tenant_id() AND public.app_has_permission('suppliers.manage'))
    );
