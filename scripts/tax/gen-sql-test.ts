/**
 * Writes supabase/tests/tax_engine_test.sql from src/shared/taxEngineCases.json:
 * the database's app_tax_document() must give every case's frozen figures.
 *   npx tsx scripts/tax/gen-sql-test.ts
 * src/shared/taxEngine.test.ts fails if the file is out of date.
 */
import fs from 'node:fs';
import cases from '../../src/shared/taxEngineCases.json';

export const SQL_TEST = 'supabase/tests/tax_engine_test.sql';
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function buildSqlTest(): string {
  const rows = (cases as any[]).map((c) => {
    const i = c.input;
    const call = `public.app_tax_document(${q(JSON.stringify(i.lines))}::jsonb, ${i.rate}, ${q(i.discountType ?? 'percent')}, ${i.discountValue ?? 0}, ${i.maxDiscountPercent ?? 'NULL'})`;
    return `SELECT is(${call}, ${q(JSON.stringify(c.expected))}::jsonb, ${q(c.name)});`;
  });
  return [
    '-- Generated by scripts/tax/gen-sql-test.ts from src/shared/taxEngineCases.json -- do not edit.',
    '-- seen-readiness-fixes-task.md P1.1: the database\'s tax engine gives the same figures as the',
    '-- browser\'s (src/shared/taxEngine.ts) on every case of the truth table, to the halala.',
    'BEGIN;',
    `SELECT plan(${rows.length});`,
    ...rows,
    'SELECT * FROM finish();',
    'ROLLBACK;',
    '',
  ].join('\n');
}

if (process.argv[1] && process.argv[1].replace(/\\/g, '/').endsWith('scripts/tax/gen-sql-test.ts')) {
  fs.writeFileSync(SQL_TEST, buildSqlTest());
  console.log(`wrote ${SQL_TEST}`);
}
