/**
 * seen-permissions-fix-task.md Phase 1: src/shared/permissionsMatrix.json is
 * the one source of the eight roles' default permissions. This builds the
 * SQL that fills public.role_default_permissions from it.
 *
 *   npx tsx scripts/permissions/gen-sql.ts            # print the block
 *   npx tsx scripts/permissions/gen-sql.ts --write    # rewrite it in the migration
 *
 * The block sits between the BEGIN/END markers in MIGRATION below;
 * src/shared/permissionsMatrix.test.ts fails if the two ever differ.
 */
import fs from 'node:fs';
import matrix from '../../src/shared/permissionsMatrix.json';

export const MIGRATION = 'supabase/migrations/20270101000000_permissions_single_source.sql';
export const BEGIN = '-- BEGIN generated by scripts/permissions/gen-sql.ts from src/shared/permissionsMatrix.json';
export const END = '-- END generated';

type Matrix = { keys: string[]; roles: Record<string, string[]> };

export function buildRoleDefaultsSql(m: Matrix = matrix as Matrix): string {
  const rows: string[] = [];
  for (const [role, allowed] of Object.entries(m.roles)) {
    const set = new Set(allowed);
    for (const key of m.keys) rows.push(`  ('${role}', '${key}', ${set.has(key)})`);
  }
  return [
    BEGIN,
    'DELETE FROM public.role_default_permissions;',
    'INSERT INTO public.role_default_permissions (role_key, permission_key, allowed) VALUES',
    rows.join(',\n') + ';',
    END,
  ].join('\n');
}

/** The generated block as it is in the migration file. */
export function blockInMigration(sql: string): string | null {
  const s = sql.indexOf(BEGIN);
  const e = sql.indexOf(END);
  return s < 0 || e < 0 ? null : sql.slice(s, e + END.length).replace(/\r\n/g, '\n');
}

if (process.argv[1] && process.argv[1].replace(/\\/g, '/').endsWith('scripts/permissions/gen-sql.ts')) {
  const block = buildRoleDefaultsSql();
  if (process.argv.includes('--write')) {
    const sql = fs.readFileSync(MIGRATION, 'utf-8').replace(/\r\n/g, '\n');
    const current = blockInMigration(sql);
    if (!current) throw new Error(`markers not found in ${MIGRATION}`);
    fs.writeFileSync(MIGRATION, sql.replace(current, block));
    console.log(`rewrote the generated block in ${MIGRATION}`);
  } else {
    console.log(block);
  }
}
