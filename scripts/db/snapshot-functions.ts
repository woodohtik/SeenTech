/**
 * The database functions as they really are (seen-stability-guardrails-task.md, phase 3).
 *
 *   npx tsx scripts/db/snapshot-functions.ts --local            # write supabase/schema/functions/ from the local DB
 *   npx tsx scripts/db/snapshot-functions.ts --local --check    # CI: fail if the snapshot differs
 *   npx tsx scripts/db/snapshot-functions.ts --linked [--check] # the same against staging (no Docker here)
 *
 * Why: a function redefined from an old migration's copy silently loses the
 * fixes made after it (create_pos_sale's ZATCA chain, app_current_tenant_id's
 * trash check). With the snapshot in git, every change to a function shows in
 * the pull request as a diff, and a redefinition starts from the snapshot --
 * never from an old migration (CLAUDE.md, "قواعد الجودة").
 *
 * One file per function name (overloads together, by their arguments), from
 * pg_get_functiondef, for every function in public that is not an
 * extension's. In GitHub Actions a difference is also an annotation on the file.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

const DIR = path.join('supabase', 'schema', 'functions');
const args = process.argv.slice(2);
const target = args.includes('--linked') ? '--linked' : '--local';
const check = args.includes('--check');

const QUERY = `
select p.proname as name,
       pg_get_function_identity_arguments(p.oid) as args,
       pg_get_functiondef(p.oid) as def
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 where n.nspname = 'public'
   and p.prokind in ('f', 'p')
   and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
 order by p.proname, pg_get_function_identity_arguments(p.oid);`;

interface Fn { name: string; args: string; def: string }

function readFunctions(): Fn[] {
  const file = path.join(tmpdir(), `snapshot-functions-${process.pid}.sql`);
  writeFileSync(file, QUERY);
  const out = execFileSync(process.env.SUPABASE_CLI || 'npx', [...(process.env.SUPABASE_CLI ? [] : ['supabase']), 'db', 'query', target, '--file', file, '--output-format', 'json'], {
    encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'], shell: process.platform === 'win32',
  });
  const start = out.indexOf('{') >= 0 && (out.indexOf('[') < 0 || out.indexOf('{') < out.indexOf('[')) ? out.indexOf('{') : out.indexOf('[');
  const parsed = JSON.parse(out.slice(start, Math.max(out.lastIndexOf('}'), out.lastIndexOf(']')) + 1));
  const rows: Fn[] = Array.isArray(parsed) ? parsed : parsed.rows;
  if (!Array.isArray(rows) || rows.length === 0) throw new Error('no functions read -- is the database up?');
  return rows;
}

/** The files the snapshot is made of: name -> content. */
export function snapshotFiles(fns: Fn[]): Map<string, string> {
  const byName = new Map<string, Fn[]>();
  for (const fn of fns) byName.set(fn.name, [...(byName.get(fn.name) ?? []), fn]);
  const files = new Map<string, string>();
  for (const [name, list] of byName) {
    const body = list
      .sort((a, b) => a.args.localeCompare(b.args))
      .map((fn) => `-- ${name}(${fn.args})\n${fn.def.replace(/\r\n/g, '\n').trimEnd()};\n`)
      .join('\n');
    files.set(`${name}.sql`, `-- Generated by scripts/db/snapshot-functions.ts -- do not edit by hand.\n-- Redefine a function from this file, never from an old migration.\n\n${body}`);
  }
  return files;
}

const files = snapshotFiles(readFunctions());

if (!check) {
  if (existsSync(DIR)) for (const f of readdirSync(DIR)) if (f.endsWith('.sql')) rmSync(path.join(DIR, f));
  mkdirSync(DIR, { recursive: true });
  for (const [name, content] of files) writeFileSync(path.join(DIR, name), content);
  console.log(`wrote ${files.size} files (${[...files.values()].reduce((n, c) => n + (c.match(/^-- \w+\(/gm)?.length ?? 0), 0)} functions) to ${DIR}`);
  process.exit(0);
}

const committed = existsSync(DIR) ? readdirSync(DIR).filter((f) => f.endsWith('.sql')) : [];
const changed: string[] = [];
const added: string[] = [];
const removed: string[] = [];
for (const [name, content] of files) {
  const p = path.join(DIR, name);
  if (!existsSync(p)) added.push(name);
  else if (readFileSync(p, 'utf8').replace(/\r\n/g, '\n') !== content) changed.push(name);
}
for (const name of committed) if (!files.has(name)) removed.push(name);

const annotate = (kind: string, name: string) => {
  if (process.env.GITHUB_ACTIONS) {
    console.log(`::error file=${DIR}/${name}::${kind}: the database function differs from the committed snapshot. Run "npx tsx scripts/db/snapshot-functions.ts --local" and commit ${DIR}/.`);
  }
};
for (const n of changed) annotate('changed', n);
for (const n of added) annotate('new function, not in the snapshot', n);
for (const n of removed) annotate('in the snapshot but not in the database', n);

if (changed.length + added.length + removed.length === 0) {
  console.log(`snapshot matches: ${files.size} function files`);
  process.exit(0);
}
console.log(`snapshot differs -- changed: ${changed.join(', ') || '-'}; new: ${added.join(', ') || '-'}; removed: ${removed.join(', ') || '-'}`);
process.exit(1);
